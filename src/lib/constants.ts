export function getLevelDescription(level?: string): string {
  if (!level) return "";
  const clean = String(level).trim().toLowerCase();
  if (clean.includes("1") || clean === "level 1" || clean === "1") return "Classes 4 to 8";
  if (clean.includes("2") || clean === "level 2" || clean === "2") return "Classes 8 to 12";
  if (clean.includes("3") || clean === "level 3" || clean === "3") return "Open for all";
  return "";
}

export function findCenterByIdOrName(centerQuery: string): ExaminationCenterInfo | undefined {
  if (!centerQuery) return undefined;
  const q = centerQuery.trim().toLowerCase();
  return EXAMINATION_CENTERS.find(
    (c) => c.id.toLowerCase() === q || c.name.toLowerCase() === q
  );
}

